// MARK: - Deterministic async barrier

/// Single-shot deterministic barrier that holds an engine-double callback in flight until the
/// test explicitly releases it.
///
/// Purpose: make "late callback after cancel / close-archive / close-window" regressions
/// deterministic instead of timing dependent. The barrier never sleeps and never polls on
/// wall-clock time; it hands over continuations directly.
actor ArchiveHostAsyncBarrier {
    private var isSuspended = false
    private var didRelease = false
    private var suspendObservers: [CheckedContinuation<Void, Never>] = []
    private var releaseWaiters: [CheckedContinuation<Void, Never>] = []

    /// Suspends the calling task until `release()` is invoked.
    func suspendUntilReleased() async {
        guard !didRelease else { return }
        isSuspended = true
        let observers = suspendObservers
        suspendObservers.removeAll()
        for observer in observers { observer.resume() }
        let bounded = boundedSuspendObservers
        boundedSuspendObservers.removeAll()
        for observer in bounded { observer.continuation.resume(returning: true) }
        await withCheckedContinuation { (continuation: CheckedContinuation<Void, Never>) in
            releaseWaiters.append(continuation)
        }
    }

    /// Suspends until the barrier observes an in-flight `suspendUntilReleased()` call.
    func waitUntilSuspended() async {
        guard !isSuspended else { return }
        await withCheckedContinuation { (continuation: CheckedContinuation<Void, Never>) in
            suspendObservers.append(continuation)
        }
    }

    /// Suspends until the barrier observes an in-flight `suspendUntilReleased()` call, bounded by
    /// `timeout`.
    ///
    /// Returns `true` when a caller suspended within the budget and `false` when the budget
    /// expired. The unbounded `waitUntilSuspended()` keeps its original semantics; this variant
    /// exists so a test can *observe* a missing event instead of waiting for it forever.
    func waitUntilSuspended(timeout: Duration) async -> Bool {
        if isSuspended { return true }
        let id = UUID()
        return await withCheckedContinuation { (continuation: CheckedContinuation<Bool, Never>) in
            boundedSuspendObservers.append(
                BoundedSuspendObserver(id: id, continuation: continuation)
            )
            // The task inherits the actor isolation, so the expiry runs on the actor itself.
            Task {
                try? await Task.sleep(for: timeout)
                self.expireBoundedSuspendObserver(id: id)
            }
        }
    }

    /// Releases every suspended caller. Idempotent.
    func release() {
        guard !didRelease else { return }
        didRelease = true
        isSuspended = false
        let waiters = releaseWaiters
        releaseWaiters.removeAll()
        for waiter in waiters { waiter.resume() }
    }

    /// A bounded observer of the "a caller suspended" event.
    private struct BoundedSuspendObserver {
        let id: UUID
        let continuation: CheckedContinuation<Bool, Never>
    }

    private var boundedSuspendObservers: [BoundedSuspendObserver] = []

    /// Resumes a bounded observer with `false` when its budget expired.
    private func expireBoundedSuspendObserver(id: UUID) {
        guard let index = boundedSuspendObservers.firstIndex(where: { $0.id == id }) else { return }
        let observer = boundedSuspendObservers.remove(at: index)
        observer.continuation.resume(returning: false)
    }
}

// MARK: - Bounded completion receipt

/// Bounded receipt for the outcome of a background operation.
///
/// A test that must not wait forever for an operation that may never complete records the
/// outcome here instead of awaiting the task directly. The wait carries an explicit budget, so
/// a missing completion is observable as `nil` instead of a hang. The receipt never cancels or
/// joins the operation it observes, and it never pretends that a timeout is an outcome: a
/// missing value is reported as `nil`.
actor ArchiveHostCompletionReceipt<Value: Sendable> {
    private var hasStored: Bool = false
    private var stored: Value?
    private var waiters: [CheckedContinuation<Value?, Never>] = []
    private var waiterIDs: [UUID] = []

    /// Records the outcome of the observed operation. The first outcome wins.
    func store(_ value: Value) {
        guard !hasStored else { return }
        hasStored = true
        stored = value
        let pending = waiters
        waiters = []
        waiterIDs = []
        for waiter in pending { waiter.resume(returning: value) }
    }

    /// The outcome recorded so far, without waiting.
    func recorded() -> Value? {
        hasStored ? stored : nil
    }

    /// Waits for the outcome, bounded by `timeout`.
    ///
    /// Returns `nil` when the budget expired before an outcome arrived. The caller keeps the
    /// responsibility to release whatever the operation is blocked on.
    func waitForValue(timeout: Duration) async -> Value? {
        if hasStored { return stored }
        let id = UUID()
        return await withCheckedContinuation { (continuation: CheckedContinuation<Value?, Never>) in
            waiters.append(continuation)
            waiterIDs.append(id)
            // The task inherits the actor isolation, so the expiry runs on the actor itself.
            Task {
                try? await Task.sleep(for: timeout)
                self.expire(id: id)
            }
        }
    }

    /// Resumes a waiter with `nil` when its budget expired.
    private func expire(id: UUID) {
        guard let index = waiterIDs.firstIndex(of: id) else { return }
        waiterIDs.remove(at: index)
        let waiter = waiters.remove(at: index)
        waiter.resume(returning: nil)
    }
}

