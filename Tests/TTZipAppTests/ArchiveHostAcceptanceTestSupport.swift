/// Shared lifecycle and fixture helpers for the MM17 archive host acceptance suites.
///
/// Contains no test methods on purpose — it exists so the two sibling suites do not have to
/// duplicate the same reset/teardown and fixture code.
@MainActor
class ArchiveHostAcceptanceTestCase: XCTestCase {

    /// Relative path of the single encrypted entry reported by the controlled driver.
    let probeEntryPath = "secret.txt"

    /// The candidate password the controlled driver accepts.
    let correctPassword = "correct-secret"

    // MARK: Lifecycle

    override func setUp() {
        super.setUp()
        MainActor.assumeIsolated {
            BrowserWindowRegistry.shared.resetForTesting()
            BrowserWindowRouter.shared.resetForTesting()
            ArchivePasswordStore.shared.clearAll()
            VFSLz4CachePool.shared.clearSession(sessionId: "mm17")
            AppErrorReporter.shared.dismiss()
        }
        UserDefaults.standard.removeObject(forKey: "TTZipRecentArchivesKey")
    }

    override func tearDown() {
        MainActor.assumeIsolated {
            BrowserWindowRegistry.shared.resetForTesting()
            BrowserWindowRouter.shared.resetForTesting()
            ArchivePasswordStore.shared.clearAll()
            VFSLz4CachePool.shared.clearSession(sessionId: "mm17")
            AppErrorReporter.shared.dismiss()
        }
        UserDefaults.standard.removeObject(forKey: "TTZipRecentArchivesKey")
        super.tearDown()
    }

    // MARK: Fixtures

    /// Creates a real, unencrypted zip fixture on disk.
    ///
    /// The fixture lives in a per-test directory under `FileManager.default.temporaryDirectory`
    /// and is removed in teardown. The host's readability gate and its background prefetch
    /// therefore run against a real file without ever touching a user archive.
    ///
    /// The *encryption* behaviour of this archive is simulated by the controlled driver.
    func makeArchiveFixture(named name: String = "locked") throws -> URL {
        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("TTZipMM17-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        addTeardownBlock { try? FileManager.default.removeItem(at: dir) }

        let payload = dir.appendingPathComponent(probeEntryPath)
        try Data("mm17 host acceptance fixture payload".utf8).write(to: payload)

        let archiveURL = dir.appendingPathComponent("\(name).zip")
        try ArchiveWriter().createArchiveSync(
            outputPath: archiveURL.path,
            format: .zip,
            level: .fastest,
            inputPaths: [payload.path]
        )
        return archiveURL
    }

    /// Creates an isolated extraction destination directory under the temporary root.
    func makeDestinationDirectory() throws -> URL {
        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("TTZipMM17Dest-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        addTeardownBlock { try? FileManager.default.removeItem(at: dir) }
        return dir
    }

    /// Asserts that a path points into the per-test temporary root.
    ///
    /// Guards the "never touch a real user archive" boundary for every source-archive
    /// operation the suites perform.
    func assertTemporaryFixturePath(_ path: String, file: StaticString = #filePath, line: UInt = #line) {
        let temporaryRoot = FileManager.default.temporaryDirectory.standardizedFileURL.path
        let standardized = URL(fileURLWithPath: path).standardizedFileURL.path
        XCTAssertTrue(
            standardized.hasPrefix(temporaryRoot),
            "Fixtures must stay inside the temporary root, got \(standardized)",
            file: file,
            line: line
        )
    }

    // MARK: - MM49 shared busy-ownership helpers

    /// Builds a controlled driver whose inspection and extraction calls are gated per archive path.
    ///
    /// Two overlapping operations can therefore be released independently, and the driver call
    /// record proves that each production chain really ran.
    func makeGatedArchiveDriver(
        inspectBarriers: [String: ArchiveHostAsyncBarrier] = [:],
        extractBarriers: [String: ArchiveHostAsyncBarrier] = [:]
    ) -> MockArchivePasswordDriver {
        let driver = MockArchivePasswordDriver()
        driver.inspectHandler = { path, _, _ in
            if let barrier = inspectBarriers[path] {
                await barrier.suspendUntilReleased()
            }
            return self.makePlainInspectResult(path: path)
        }
        driver.quickExtractHandler = { path, destinationDir, password, _ in
            if let barrier = extractBarriers[path] {
                await barrier.suspendUntilReleased()
            }
            return ExtractResult(
                archivePath: path,
                destinationDir: destinationDir,
                durationSeconds: 0.001,
                unlockedPassword: password,
                isVaultUnlocked: false
            )
        }
        return driver
    }

    /// Builds a plain (unencrypted) inspection result for the controlled driver double.
    func makePlainInspectResult(path: String) -> InspectResult {
        InspectResult(
            archivePath: path,
            format: "zip",
            entries: [
                ArchiveEntry(
                    path: probeEntryPath,
                    uncompressedSize: 128,
                    isDirectory: false,
                    modificationDate: Date(timeIntervalSince1970: 1_700_000_000),
                    isEncrypted: false,
                    compressedSize: 128,
                    crc32: 0x1234_5678
                )
            ],
            totalUncompressedBytes: 128,
            totalCompressedBytes: 128,
            unlockedPassword: nil
        )
    }

    /// Builds an inspection result whose single entry is encrypted.
    ///
    /// The browse password probe needs an encrypted entry to produce a verified outcome.
    func makeEncryptedInspectResult(path: String) -> InspectResult {
        InspectResult(
            archivePath: path,
            format: "zip",
            entries: [
                ArchiveEntry(
                    path: probeEntryPath,
                    uncompressedSize: 128,
                    isDirectory: false,
                    modificationDate: Date(timeIntervalSince1970: 1_700_000_000),
                    isEncrypted: true,
                    compressedSize: 128,
                    crc32: 0x1234_5678
                )
            ],
            totalUncompressedBytes: 128,
            totalCompressedBytes: 128,
            unlockedPassword: nil
        )
    }


}

/// Narrow command double whose execution waits for a barrier.
///
/// It implements only the protocol surface the host uses, so a test can drive the real
/// `executeCommand` entry point without reusing a type from another test target.
struct GatedArchiveCommand: ArchiveCommandProtocol {
    let barrier: ArchiveHostAsyncBarrier
    let commandId: String = "mm49-busy-command"

    var description: String { "Gated archive command" }
    var isUndoable: Bool { false }

    func execute() async throws -> CommandResult {
        await barrier.suspendUntilReleased()
        return CommandResult(commandId: commandId, success: true, message: "gated command finished")
    }

    func undo() async throws {}
}


// MARK: - MM49 bounded scenario lifetime

struct ArchiveBusyObservationFailure: Error, Sendable {
    let detail: String
}

struct ArchiveBusyObservedTask<Value: Sendable>: Sendable {
    let task: Task<Void, Never>
    let receipt: ArchiveHostCompletionReceipt<Result<Value, ArchiveBusyObservationFailure>>
}

/// Owns only the controlled test lifetime, never production busy identities.
/// Snapshots are recorded while operations overlap; assertions run after all gates are released.
@MainActor
final class ArchiveBusyTestScenario {
    private let budget: Duration = .seconds(2)
    private var barriers: [ArchiveHostAsyncBarrier] = []
    private var completions: [(Task<Void, Never>, @MainActor () async -> Bool)] = []
    private var assertions: [@MainActor () -> Void] = []

    func barrier() -> ArchiveHostAsyncBarrier {
        let barrier = ArchiveHostAsyncBarrier()
        barriers.append(barrier)
        return barrier
    }

    func start<Value: Sendable>(
        _ operation: @escaping @MainActor () async throws -> Value
    ) -> ArchiveBusyObservedTask<Value> {
        let receipt = ArchiveHostCompletionReceipt<Result<Value, ArchiveBusyObservationFailure>>()
        let task = Task { @MainActor in
            do {
                let result = try await operation()
                await receipt.store(.success(result))
            } catch {
                await receipt.store(.failure(ArchiveBusyObservationFailure(detail: String(describing: error))))
            }
        }
        let completionBudget = budget
        completions.append((task, { await receipt.waitForValue(timeout: completionBudget) != nil }))
        return ArchiveBusyObservedTask(task: task, receipt: receipt)
    }

    func entered(_ barrier: ArchiveHostAsyncBarrier) async throws {
        guard await barrier.waitUntilSuspended(timeout: budget) else {
            throw ArchiveBusyObservationFailure(detail: "Controlled driver did not enter its barrier")
        }
    }

    func finish<Value: Sendable>(_ observation: ArchiveBusyObservedTask<Value>) async throws -> Value {
        guard let outcome = await observation.receipt.waitForValue(timeout: budget) else {
            throw ArchiveBusyObservationFailure(detail: "Controlled operation did not complete within its budget")
        }
        return try outcome.get()
    }

    func expect(
        _ actual: Bool, _ message: String,
        file: StaticString = #filePath, line: UInt = #line
    ) {
        assertions.append { XCTAssertTrue(actual, message, file: file, line: line) }
    }

    func expectEqual<Value: Equatable>(
        _ actual: Value, _ expected: Value, _ message: String,
        file: StaticString = #filePath, line: UInt = #line
    ) {
        assertions.append { XCTAssertEqual(actual, expected, message, file: file, line: line) }
    }

    func recordFailure(_ error: Error, file: StaticString, line: UInt) {
        let detail = String(describing: error)
        assertions.append { XCTFail(detail, file: file, line: line) }
    }

    /// Always release first. A missing receipt can fail the test but cannot make cleanup join forever.
    func releaseAndAssert() async {
        for barrier in barriers { await barrier.release() }
        for (task, completed) in completions {
            if !(await completed()) {
                task.cancel()
                assertions.append { XCTFail("Operation did not complete after all controlled gates were released") }
            }
        }
        for assertion in assertions { assertion() }
    }
}

extension ArchiveHostAcceptanceTestCase {
    func withBusyScenario(
        file: StaticString = #filePath, line: UInt = #line,
        _ body: @MainActor (ArchiveBusyTestScenario) async throws -> Void
    ) async {
        let scenario = ArchiveBusyTestScenario()
        do { try await body(scenario) }
        catch { scenario.recordFailure(error, file: file, line: line) }
        await scenario.releaseAndAssert()
    }

    /// Count the real call by its source identity, not a fabricated empty destination tuple.
    func quickExtractCallCount(_ driver: MockArchivePasswordDriver, path: String) -> Int {
        driver.calls.filter {
            if case .quickExtract(let recorded, _, _, _) = $0.kind { return recorded == path }
            return false
        }.count
    }

    func hasExpectedQuickExtractDestination(_ driver: MockArchivePasswordDriver, archiveURL: URL) -> Bool {
        let expected = archiveURL.deletingLastPathComponent()
            .appendingPathComponent(archiveURL.deletingPathExtension().lastPathComponent).path
        return driver.calls.contains {
            if case .quickExtract(let path, let destination, let password, _) = $0.kind {
                return path == archiveURL.path && destination == expected && password == nil
            }
            return false
        }
    }
}
